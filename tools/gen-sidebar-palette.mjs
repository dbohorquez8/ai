#!/usr/bin/env node
// Generates plugins/bridge/hooks/core/palette.generated.ts from the Workspace design tokens.
// Usage: node tools/gen-sidebar-palette.mjs <path to docs/design-system/tokens.css> [output path]
// No dependencies: OKLCH -> OKLab -> linear sRGB -> sRGB (clamped); color-mix(in oklab) is a linear OKLab mix.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const [, , source, outArg] = process.argv
if (!source) {
  console.error('usage: gen-sidebar-palette.mjs <tokens.css> [out.ts]')
  process.exit(2)
}
const out = outArg ?? resolve(here, '../plugins/bridge/hooks/core/palette.generated.ts')

const css = readFileSync(source, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')

/** Declarations of the block whose selector list contains `selector` as a whole token. */
const blockOf = (selector) => {
  const vars = {}
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selectors = m[1].split(',').map((s) => s.trim())
    if (!selectors.includes(selector)) continue
    for (const d of m[2].matchAll(/(--ws-[a-z0-9-]+)\s*:\s*([^;]+);/g)) vars[d[1]] = d[2].trim()
  }
  return vars
}

// OKLab (L, a, b) from OKLCH
const labOfLch = (L, C, H) => [L, C * Math.cos((H * Math.PI) / 180), C * Math.sin((H * Math.PI) / 180)]
const linearOfLab = ([L, a, b]) => {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
}
const encode = (c) => {
  const v = Math.min(1, Math.max(0, c))
  return v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055
}
const hexOfLab = (lab) =>
  '#' + linearOfLab(lab).map((c) => Math.round(encode(c) * 255).toString(16).padStart(2, '0')).join('')

/** Splits a function's arguments on top-level commas. */
const splitTop = (text) => {
  const parts = []
  let depth = 0
  let cur = ''
  for (const ch of text) {
    if (ch === '(') depth++
    if (ch === ')') depth--
    if (ch === ',' && depth === 0) {
      parts.push(cur.trim())
      cur = ''
    } else cur += ch
  }
  parts.push(cur.trim())
  return parts
}

const labOf = (value, scope) => {
  const v = value.trim()
  let m = v.match(/^var\((--ws-[a-z0-9-]+)\)$/)
  if (m) {
    if (!(m[1] in scope)) throw new Error(`unresolved ${m[1]}`)
    return labOf(scope[m[1]], scope)
  }
  m = v.match(/^oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)\s*\)$/)
  if (m) return labOfLch(Number(m[1]) / 100, Number(m[2]), Number(m[3]))
  m = v.match(/^color-mix\(\s*in oklab\s*,([\s\S]*)\)$/)
  if (m) {
    const [a, b] = splitTop(m[1])
    const pa = a.match(/^([\s\S]*?)\s+([\d.]+)%$/)
    if (!pa) throw new Error(`mix needs a percentage: ${v}`)
    const p = Number(pa[2]) / 100
    const A = labOf(pa[1], scope)
    const B = labOf(b, scope)
    return A.map((x, i) => x * p + B[i] * (1 - p))
  }
  throw new Error(`unsupported value: ${v}`)
}

const root = blockOf(':root')
const scopes = { light: { ...root, ...blockOf('.light') }, dark: { ...root, ...blockOf('.dark') } }
const NAMES = {
  red: 'red-text', orange: 'orange-text', yellow: 'yellow', green: 'green-text', blue: 'blue-text', violet: 'violet-text',
  gray: 'gray-text', redPill: 'red-pill', grayPill: 'gray-pill', waitingRow: 'orange-bg', fill: 'tint-base',
}

let body = ''
for (const mode of ['dark', 'light']) {
  body += `  ${mode}: {\n`
  for (const [key, token] of Object.entries(NAMES)) body += `    ${key}: '${hexOfLab(labOf(`var(--ws-${token})`, scopes[mode]))}',\n`
  body += '  },\n'
}
writeFileSync(
  out,
  `// Generated by tools/gen-sidebar-palette.mjs from the Workspace design tokens (docs/design-system/tokens.css). Do not edit.\n\nexport const GENERATED = {\n${body}} as const\n`,
)
console.log(`wrote ${out}`)
